const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const {installBrowserAuth,user}=require('./test_helpers/browser-auth.cjs');
const tick=()=>new Promise(r=>setTimeout(r,25));
let controller,calls=0,mode='offline',opened;
const deferred=[];
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{runScripts:'dangerously',url:'https://example.test/',beforeParse(w){
  controller=installBrowserAuth(w,{signedIn:false,admin:false});
  w.fetch=async(url,options)=>{if(!options?.body)return{ok:true,json:async()=>({ok:true})};calls++;if(mode==='offline')throw new Error('network unavailable');if(mode==='deferred')return new Promise(resolve=>deferred.push(json=>resolve({ok:true,json:async()=>json})));return{ok:true,json:async()=>mode==='auth-error'?{ok:false,authRequired:true,retryable:false,error:'Iniciá sesión'}:{ok:true}};};
  w.HTMLFormElement.prototype.submit=function(){opened=JSON.parse(this.elements.reportRequest.value);};
}});
const w=dom.window,d=w.document,$=id=>d.getElementById(id);
(async()=>{
  await tick();assert.equal($('enviar').disabled,true,'anonymous form cannot create records');assert.equal($('reportes').hidden,true);
  $('login-google').click();$('login-google').click();await tick();
  assert.equal(controller.popupCalls,1,'a double click must open only one Google sign-in flow');
  controller.setUser(user());await tick();
  assert.equal($('promotor').readOnly,true);assert.equal($('promotor').value,'María González');assert.equal($('reportes').hidden,true);
  assert.equal($('ocr-token'),null,'Google login replaces shared OCR key');assert.equal($('scan-btn').disabled,false);
  $('nombre').value='Queued visitor';d.querySelector('input[name=calif]').checked=true;
  $('f').dispatchEvent(new w.Event('submit',{cancelable:true}));await tick();
  let queued=w.eval('getCola()');assert.equal(queued.length,1);assert.equal(queued[0].operadorUid,'operator-uid');
  assert(!JSON.stringify(queued).includes('firebase-fixture-'),'bearer credentials never enter the durable queue');
  const before=calls;controller.setUser(user('other-uid','other@gmail.com'));await tick();mode='ok';await w.reintentar(true);
  assert.equal(calls,before,'another account cannot submit the original owner’s pending record');assert.equal(w.eval('getCola()').length,1);
  controller.setUser(user());await tick();await w.reintentar(true);assert.equal(w.eval('getCola()').length,0);
  controller.setUser(user('admin-uid','jaimehuang168@gmail.com','Jaime'));await tick();assert.equal($('reportes').hidden,false);
  $('ver-hoy').click();await tick();assert.equal(opened.idToken,'firebase-fixture-admin-uid');assert(!('token' in opened));
  mode='auth-error';$('nombre').value='Keep after revoked session';d.querySelector('input[name=calif]').checked=true;
  $('f').dispatchEvent(new w.Event('submit',{cancelable:true}));await tick();
  assert.equal(w.eval('getCola()').length,1,'authentication errors must never discard a durable record');assert.equal($('enviar').disabled,true);
  mode='offline';controller.setUser(user());await tick();mode='deferred';
  $('nombre').value='Original account visitor';d.querySelector('input[name=calif]').checked=true;
  $('f').dispatchEvent(new w.Event('submit',{cancelable:true}));await tick();
  controller.setUser(user('next-uid','next@gmail.com'));await tick();
  $('nombre').value='New account draft';$('nombre').dispatchEvent(new w.Event('input',{bubbles:true}));
  deferred.shift()({ok:true});await tick();
  assert.equal($('nombre').value,'New account draft','a late response must not clear the next account’s form');
  Object.defineProperty($('tarjeta-file'),'files',{value:[new w.File(['test'],'card.jpg',{type:'image/jpeg'})],configurable:true});
  w.comprimirImagen=async()=>({b64:'/9j/AAAA',thumb:'data:image/jpeg;base64,/9j/AAAA'});
  const scan=w.escanearTarjeta();await tick();
  controller.setUser(user('third-uid','third@gmail.com'));await tick();
  $('nombre').value='Third account draft';$('nombre').dispatchEvent(new w.Event('input',{bubbles:true}));
  deferred.shift()({ok:true,datos:{nombre:'Wrong previous card'},imagen:'https://drive.google.com/file/d/previous/view'});await scan;
  assert.equal($('nombre').value,'Third account draft','late OCR must not fill a different account’s form');assert.equal($('tarjetaUrl').value,'');
  mode='offline';controller.setUser(user());await tick();
  $('nombre').value='Original owner pending';d.querySelector('input[name=calif]').checked=true;
  $('f').dispatchEvent(new w.Event('submit',{cancelable:true}));await tick();
  mode='deferred';const resend=w.reintentar(true);await tick();
  controller.setUser(user('latest-uid','latest@gmail.com'));await tick();
  deferred.shift()({ok:false,authRequired:true,retryable:false,error:'Old session expired'});await resend;
  assert.equal($('enviar').disabled,false,'an old retry failure cannot sign out the new account');
  assert($('sesion-usuario').textContent.includes('latest@gmail.com'));
  console.log('PASS signed-in attribution, administrator controls, per-owner offline queue, secret-free storage, revoked-session preservation');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>w.close());
